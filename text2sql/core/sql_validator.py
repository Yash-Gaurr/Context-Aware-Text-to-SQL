"""
sql_validator.py
------------------
MODULE: SQL Validator

Nothing generated by sql_generator.py reaches the database without passing
through here first. This is a small, hand-written checker (not an external
SQL-parsing library) so every rule is visible and explainable in a viva.

Checks performed, in order:
  1. Exactly one statement (blocks "SELECT 1; DROP TABLE ..." stacking).
  2. Statement must start with SELECT (read-only requirement, brief #4).
  3. Statement must not contain any destructive/DDL/DML keyword, anywhere
     (defence in depth, not just checking the first word).
  4. Every table name referenced must exist in the schema (SchemaManager) --
     catches generator bugs / hallucinated tables before execution.

validate() returns (is_valid: bool, message: str). On failure, message
explains exactly what was wrong, which query_handler.py uses to attempt a
correction pass instead of ever executing unsafe SQL.
"""

import re
from typing import Tuple
from core.schema_manager import SchemaManager

FORBIDDEN_KEYWORDS = [
    "DROP", "DELETE", "TRUNCATE", "ALTER", "UPDATE", "INSERT", "REPLACE",
    "CREATE", "ATTACH", "DETACH", "PRAGMA", "VACUUM", "REINDEX", "GRANT",
    "REVOKE",
]

_KEYWORD_RE = {kw: re.compile(rf"\b{kw}\b", re.IGNORECASE) for kw in FORBIDDEN_KEYWORDS}
_TABLE_REF_RE = re.compile(r"\b(?:FROM|JOIN)\s+([a-zA-Z_][a-zA-Z0-9_]*)", re.IGNORECASE)

_schema = SchemaManager()


def validate(sql: str) -> Tuple[bool, str]:
    if not sql or not sql.strip():
        return False, "Generated SQL is empty."

    cleaned = sql.strip()

    # 1. Single statement only ------------------------------------------------
    # Allow a single optional trailing semicolon, but nothing after it.
    body = cleaned[:-1] if cleaned.endswith(";") else cleaned
    if ";" in body:
        return False, "Multiple SQL statements are not allowed (possible statement stacking)."

    # 2. Must be a SELECT -------------------------------------------------------
    if not re.match(r"^\s*SELECT\b", body, re.IGNORECASE):
        return False, "Only read-only SELECT queries are allowed."

    # 3. No destructive keywords anywhere in the statement -----------------------
    for kw, pattern in _KEYWORD_RE.items():
        if pattern.search(body):
            return False, f"Query contains a forbidden keyword: {kw}."

    # 4. Referenced tables must exist in the schema -------------------------------
    known_tables = set(_schema.table_names())
    referenced = set(m.group(1).lower() for m in _TABLE_REF_RE.finditer(body))
    unknown = referenced - known_tables
    if unknown:
        return False, f"Query references unknown table(s): {', '.join(sorted(unknown))}."

    return True, "OK"
